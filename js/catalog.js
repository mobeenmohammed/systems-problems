/* ============================================================
   catalog.js — the problem index, the concept graph, and lazily
   fetched problem and solution files.

   data/index.json is generated by scripts/build-index.mjs and
   carries metadata only: enough to list, search and filter every
   problem without downloading any of them. A problem's statement
   arrives when you open it, and its answer key only when you
   submit.

   That split is also the only answer-hiding a static site can
   honestly offer: the key is not in the page you are reading, so
   seeing it has to be a decision rather than an accident.
   ============================================================ */

const Catalog = (() => {

  const INDEX_URL     = 'data/index.json';
  const CONCEPTS_URL  = 'data/concepts.json';
  const TRACKS_URL    = 'data/tracks.json';
  const COURSES_URL   = 'data/courses.json';
  const WEEKLY_URL    = 'data/weekly.json';
  const RESOURCES_URL = 'data/resources.json';

  const TYPES = [
    { id: 'mcq',     label: 'Multiple choice', note: 'One right answer.' },
    { id: 'multi',   label: 'Select all',      note: 'Several right answers, partial credit.' },
    { id: 'numeric', label: 'A number',        note: 'A figure, within a tolerance.' },
    { id: 'short',   label: 'Short answer',    note: 'A word or a flag.' },
    { id: 'order',   label: 'Put in order',    note: 'Arrange the steps.' },
    { id: 'match',   label: 'Match pairs',     note: 'Pair the two columns.' },
    { id: 'predict', label: 'Predict output',  note: 'Say exactly what it prints.' },
    { id: 'locate',  label: 'Find the bug',    note: 'Click the offending line.' },
    { id: 'code',    label: 'Write code',      note: 'Compiled and run against tests.' },
    { id: 'hdl',     label: 'Design hardware', note: 'Written in SystemVerilog and simulated against a testbench.' },
  ];
  const TYPE_BY_ID = Object.fromEntries(TYPES.map(t => [t.id, t]));

  /* Types you write something runnable for, as opposed to answer. The
     "Coding exercises" door and the catalogue's own counts both ask
     this question, and they used to ask it as `type === 'code'` in two
     different files. */
  const WRITTEN_TYPES = new Set(['code', 'hdl']);

  /* What people call each kind, for the search. Not shown anywhere: it
     exists so that typing the obvious word finds the thing. */
  const TYPE_WORDS = {
    hdl: ['systemverilog', 'verilog', 'hdl', 'rtl', 'hardware', 'digital logic',
      'simulation', 'testbench', 'waveform'],
    code: ['code', 'program', 'coding exercise'],
    mcq: ['multiple choice', 'quiz'],
    multi: ['select all', 'multiple choice'],
    proof: ['proof'],
  };

  /* The languages an exercise can declare, in the order a filter should
     offer them, and what each is called in front of a reader. Here rather
     than in the code type module because the catalogue filters on it and
     two maps that have to agree eventually disagree. The build validates
     every problem's `langs` against this same list. */
  /* `sv` was deliberately kept OUT of this list, on the reasoning that a
     hardware exercise is not "solvable in SystemVerilog" in the way the
     filter means — it is solvable in nothing else.

     That reasoning was wrong, and the symptom was that the language
     filter offered C++, Python, Rust and JavaScript and a reader
     looking for SystemVerilog concluded there was none. The filter
     means "exercises you can write in this language", and there are
     four. Nothing else follows from listing it: only `hdl` problems
     declare `sv`, so no C++ exercise offers to switch to it. */
  const LANGS = ['cpp', 'python', 'rust', 'js', 'sv'];
  const LANG_LABEL = {
    js: 'JavaScript', python: 'Python', cpp: 'C++', rust: 'Rust',
    sv: 'SystemVerilog',
  };

  let index     = [];
  let byId      = {};
  let concepts  = {};
  let tracks    = [];
  let courses   = {};
  let weekly    = { weeks: [] };
  let resources = { topics: {} };
  let loadError = null;

  const fullCache = new Map();
  const solCache  = new Map();

  async function init() {
    const [idx, con, trk, crs, wk, res] = await Promise.all([
      fetchJson(INDEX_URL),
      fetchJson(CONCEPTS_URL),
      fetchJson(TRACKS_URL),
      fetchJson(COURSES_URL),
      fetchJson(WEEKLY_URL),
      fetchJson(RESOURCES_URL),
    ]);
    if (idx.ok) {
      index = Array.isArray(idx.data) ? idx.data : (idx.data.problems || []);
      byId = Object.fromEntries(index.map(p => [p.id, p]));
    } else {
      loadError = idx.error;
    }
    concepts = con.ok ? con.data : {};
    /* These three are extras: the site is perfectly usable without them, so a
       missing or malformed file leaves the feature out rather than breaking
       the page. */
    tracks    = trk.ok && Array.isArray(trk.data) ? trk.data : [];
    courses   = crs.ok && crs.data && typeof crs.data === 'object' ? crs.data : {};
    weekly    = wk.ok && wk.data && Array.isArray(wk.data.weeks) ? wk.data : { weeks: [] };
    resources = res.ok && res.data && res.data.topics ? res.data : { topics: {} };

    return { index, concepts, tracks, courses, weekly, resources, loadError };
  }

  async function fetchJson(url) {
    try {
      const res = await fetch(url, { cache: 'no-cache' });
      if (!res.ok) return { ok: false, error: `${res.status} ${res.statusText}` };
      return { ok: true, data: await res.json() };
    } catch (err) {
      /* Opening index.html straight off disk blocks fetch in some browsers.
         That is a legitimate way to look at the page, so it is reported
         rather than thrown. */
      return { ok: false, error: String(err && err.message || err) };
    }
  }

  /* ---------------- listing ---------------- */

  const all = () => index;
  const meta = id => byId[id] || null;

  /* A second pool of problems, reachable BY ID and not listed.

     The assessment bank registers itself here. `get` and `meta` then
     work for one of its problems, so the ordinary problem page renders
     it with no changes at all — and `all()` does not contain it, so the
     catalogue cannot list it, no filter can reach it, and every count
     on the site stays a count of the practice catalogue.

     That separation is the whole requirement: a problem you have
     already met in practice is not an assessment. */
  const pooled = new Set();

  function registerPool(metas) {
    for (const m of metas || []) {
      if (!m || !m.id || byId[m.id]) continue;
      byId[m.id] = m;
      pooled.add(m.id);
    }
    return pooled.size;
  }

  const isPooled = id => pooled.has(id);

  function list(filter = {}) {
    const q = String(filter.q || '').trim().toLowerCase();
    const terms = q ? q.split(/\s+/) : [];

    return index.filter(p => {
      /* Subject is the coarsest filter and the one the top bar switches.
         A search term overrides it on purpose: looking for "bayes" while
         Systems is selected should find it rather than silently returning
         nothing, and the catalog says when that has happened. */
      if (filter.subject && !terms.length && p.subject !== filter.subject) return false;

      /* The coarse split the landing page links to: do you write code, or
         answer a question. Like subject, a search overrides it — looking
         for something by name should find it whichever door you came
         through. */
      if (filter.kind && !terms.length) {
        /* A hardware exercise is one you write and run, so it belongs
           under "Coding exercises". It was excluded because the test was
           `type === 'code'` — which meant the four SystemVerilog
           exercises were in the catalogue and in no door that leads to
           it. That was most of why they could not be found. */
        const isCode = WRITTEN_TYPES.has(p.type);
        if (filter.kind === 'code' && !isCode) return false;
        if (filter.kind === 'questions' && isCode) return false;
      }
      if (filter.topic      && p.topic      !== filter.topic)      return false;
      if (filter.difficulty && p.difficulty !== filter.difficulty) return false;
      if (filter.type       && p.type       !== filter.type)       return false;
      if (filter.lane       && (p.lane || 'core') !== filter.lane)  return false;
      /* Debugging challenges: a starter that is a complete wrong program
         rather than a hole to fill. They stay in their own topics and
         tracks — this is a way to ask for them, not a place to put
         them. */
      if (filter.debugging  && !p.debugging)                        return false;
      if (filter.project    && !p.project)                          return false;

      /* "Can be solved in this language" — a property of the exercise, not
         of what is installed. A problem declaring C++ only stays C++ only
         whether or not a Python runner exists, and a question has no
         language at all, so asking for one excludes it. */
      if (filter.lang && !(p.langs || []).includes(filter.lang)) return false;

      if (filter.status) {
        const r = Store.record(p.id);
        if (filter.status === 'flagged') {
          const due = r.reviewOn && r.reviewOn <= Store.todayISO();
          if (!r.flagged && !due) return false;
        } else if (r.status !== filter.status) return false;
      }

      if (terms.length) {
        /* The words somebody actually types. Searching "SystemVerilog"
           used to find nothing at all, and "Verilog" found the two older
           C++ simulations of hardware rather than the four exercises
           written in it — because the haystack was the title, the topic,
           the bare type id and the tags, and none of those is the name
           of the language.

           So the language names go in, and each type carries the words
           people use for it. One list, beside the types themselves. */
        const hay = (`${p.title} ${p.topic} ${p.subject || ''} ${p.type} `
          + `${(p.langs || []).map(l => LANG_LABEL[l] || l).join(' ')} `
          + `${(TYPE_WORDS[p.type] || []).join(' ')} `
          + `${(p.tags || []).join(' ')} `
          + `${p.debugging ? 'debugging debug bug fix broken faulty' : ''} `
          + `${p.project ? `project milestone ${p.project.id} ${p.project.title}` : ''}`).toLowerCase();
        if (!terms.every(t => hay.includes(t))) return false;
      }
      return true;
    });
  }

  /* Difficulty, then title — so a topic reads as a path through it rather
     than as whatever order the files happened to be walked in. */
  const ORDER = { beginner: 0, intermediate: 1, advanced: 2 };
  function sorted(rows) {
    return [...rows].sort((a, b) =>
      (ORDER[a.difficulty] ?? 9) - (ORDER[b.difficulty] ?? 9) ||
      a.title.localeCompare(b.title));
  }

  /* ---------------- one problem ---------------- */

  const pathFor     = p => `problems/${p.topic}/${p.id}.json`;
  const solPathFor  = id => `solutions/${id}.json`;

  async function get(id) {
    if (fullCache.has(id)) return fullCache.get(id);
    const m = byId[id];
    if (!m) return null;
    const res = await fetchJson(pathFor(m));
    if (!res.ok) return null;
    /* The index is generated from the problem file, so where they disagree the
       file is right — but id, topic and difficulty are what progress is keyed
       and scored on, so they come from the index to stay consistent with it. */
    const full = { ...res.data, id: m.id, topic: m.topic, difficulty: m.difficulty, type: m.type };
    fullCache.set(id, full);
    return full;
  }

  async function solution(id) {
    if (solCache.has(id)) return solCache.get(id);
    const res = await fetchJson(solPathFor(id));
    if (!res.ok) return null;
    solCache.set(id, res.data);
    return res.data;
  }

  /* ---------------- concepts ---------------- */

  const concept = id => concepts[id] || null;
  const allConcepts = () => Object.entries(concepts).map(([id, c]) => ({ id, ...c }));

  /* Prerequisites are transitive: a concept names what it needs, and what it
     needs names what *it* needs. Returned deepest-first, which is reading
     order — you cannot start in the middle of a chain.

     Cycles are tolerated rather than trusted: content.test.mjs fails the build
     on one, but a cycle here must not hang the page. */
  function chain(rootId) {
    const out = [];
    const seen = new Set();
    const visiting = new Set();

    (function walk(id) {
      if (seen.has(id) || visiting.has(id) || !concepts[id]) return;
      visiting.add(id);
      for (const need of concepts[id].needs || []) walk(need);
      visiting.delete(id);
      seen.add(id);
      out.push({ id, ...concepts[id] });
    })(rootId);

    return out;
  }

  /* Every concept a problem rests on, in reading order, each carrying the
     problem's own sentence on why it is needed here. */
  function prereqsFor(problem) {
    const why = {};
    for (const p of problem.prereqs || []) why[p.concept] = p.why || '';
    const seen = new Set();
    const out = [];
    for (const p of problem.prereqs || []) {
      for (const c of chain(p.concept)) {
        if (seen.has(c.id)) continue;
        seen.add(c.id);
        out.push({ ...c, why: why[c.id] || '', direct: Object.hasOwn(why, c.id) });
      }
    }
    return out;
  }

  /* How much of a concept's reading list you have ticked off. */
  function readProgress(conceptId) {
    const c = concepts[conceptId];
    const total = (c && c.readings || []).length;
    if (!total) return { read: 0, total: 0, fraction: 1 };
    let read = 0;
    for (let i = 0; i < total; i += 1) if (Store.hasRead(conceptId, i)) read += 1;
    return { read, total, fraction: read / total };
  }

  /* ---------------- tracks ----------------

     A track is an ordered list of problem ids. Ids that are not in the catalog
     are dropped rather than rendered as dead rows, so a track can name a
     problem that has not been written yet without breaking the page. */

  function allTracks(subject = null) {
    const rows = tracks.map(t => {
      const problems = (t.problems || []).filter(id => byId[id]);
      /* A track's subject is the subject of the problems in it, so there is
         no field to keep in step with the problem files. A track spanning
         both would show in both, which is the honest answer. */
      const subjects = [...new Set(problems.map(id => byId[id].subject))];
      return {
        ...t,
        problems,
        subjects,
        missing: (t.problems || []).filter(id => !byId[id]).length,
      };
    });
    return subject ? rows.filter(t => t.subjects.includes(subject)) : rows;
  }

  const track = id => allTracks().find(t => t.id === id) || null;

  /* Solved count and the next unsolved problem, which is the only thing a
     track really has to answer. */
  function trackProgress(t) {
    const rows = (t.problems || []).map(id => ({ id, meta: byId[id], record: Store.record(id) }));
    const done = rows.filter(r => r.record.status === 'solved').length;
    const touched = rows.filter(r => r.record.status !== 'unsolved').length;
    const next = rows.find(r => r.record.status !== 'solved') || null;

    /* Three states, and the middle one has to be earned. A track nobody has
       opened was being labelled "in progress", which made every track look
       half-done and the label worth nothing. */
    const state = !rows.length ? 'empty'
      : done === rows.length ? 'completed'
      : touched > 0 ? 'attempted'
      : 'not-started';

    /* Resuming beats starting: a problem opened and not finished is where the
       reader actually left off, so it outranks the next untouched one. */
    const resume = rows.find(r => r.record.status === 'attempted')
      || rows.find(r => r.record.status === 'read')
      || next;

    return {
      done, touched, total: rows.length, rows, next, resume, state,
      fraction: rows.length ? done / rows.length : 0,
    };
  }

  const TRACK_STATE_LABEL = {
    'not-started': 'Not started',
    attempted: 'Attempted',
    completed: 'Completed',
    empty: 'Empty',
  };

  /* ---------------- the week's problem ----------------

     The latest entry whose Monday has arrived. Entries dated in the future are
     ignored, so the schedule can run ahead of today without giving anything
     away. */
  function thisWeek(today = Store.todayISO()) {
    const past = (weekly.weeks || [])
      .filter(w => w.from && w.from <= today && byId[w.problem])
      .sort((a, b) => a.from.localeCompare(b.from));
    if (!past.length) return null;
    const w = past[past.length - 1];
    return { ...w, meta: byId[w.problem], weekOf: w.from };
  }

  /* ---------------- resources ---------------- */

  const topicResources = topicId => (resources.topics || {})[topicId] || null;
  const allResources = () => Object.entries(resources.topics || {}).map(([id, r]) => ({ id, ...r }));

  /* ---------------- concepts, the other way round ----------------

     A problem names the concepts it rests on. The reading list wants the
     reverse — which exercises practise this concept — so that reading a
     chapter has a visible next step rather than being its own reward. Built
     from the index, which already carries each problem's prereq concept ids,
     so no problem file has to be fetched. Cached, because the reading view
     calls it once per concept. */
  let reverseIndex = null;

  function problemsForConcept(conceptId) {
    if (!reverseIndex) {
      reverseIndex = {};
      for (const p of index) {
        for (const c of p.prereqs || []) {
          (reverseIndex[c] = reverseIndex[c] || []).push(p);
        }
      }
      for (const list of Object.values(reverseIndex)) {
        list.sort((a, b) =>
          (ORDER[a.difficulty] ?? 9) - (ORDER[b.difficulty] ?? 9) ||
          a.title.localeCompare(b.title));
      }
    }
    return reverseIndex[conceptId] || [];
  }

  /* ---------------- a track as a tree ----------------

     A track lists problems. Each problem names the concepts it rests on,
     and each concept names what it rests on in turn. The union of all of
     that, closed under `needs`, is what the track actually teaches, and
     the prerequisite edges are what put it in order.

     It is a DAG rather than a tree: twelve of the hundred and fifteen
     concepts have more than one prerequisite. Each node is therefore hung
     under its *deepest* prerequisite, which guarantees that everything a
     node needs appears somewhere above it, and the edges that did not
     become the parent are carried on the node as `alsoNeeds` rather than
     dropped. A clean tree with the awkward edges deleted would be a nicer
     picture and a false one.

     Cycles are tolerated rather than trusted, as in chain(): depth()
     stops at a node already being measured instead of recursing forever.
     content.test.mjs is what actually forbids them. */

  const treeCache = {};

  /* ---------------- courses ----------------

     A track is a list of problems. A COURSE is the shape of a subject:
     chapters in the order the lecture notes have them, and inside each
     chapter the sections in the order they are introduced. The two are
     different objects and are kept in different files, because the
     answer to "what is in this unit" is not the answer to "what should
     I attempt".

     Where a track names a course, the tree is drawn from the COURSE —
     every concept of it, whether or not a problem in the track happens
     to rest on that one. A reader looking at the Metric Spaces tree
     wants the unit, including the parts the notes mark non-examinable
     and the parts nothing has been set on yet. */

  const allCourses = () => courses;
  const course = id => courses[id] || null;
  const courseOf = (trackId) => {
    const t = track(trackId);
    return t && t.course ? courses[t.course] || null : null;
  };
  const chapterConcepts = (c) =>
    (c.chapters || []).flatMap(ch => ch.concepts || []);

  /* Which chapters the reader has folded shut, per track. A fold is a
     view of the picture rather than a fact about it, so it is a
     preference and it is keyed by track. */
  const FOLD_PREF = 'learnChapters';
  function foldedChapters(trackId) {
    const all = Store.pref(FOLD_PREF, null) || {};
    const mine = all[trackId];
    return new Set(Array.isArray(mine) ? mine : []);
  }
  function setFoldedChapters(trackId, set) {
    const all = { ...(Store.pref(FOLD_PREF, null) || {}) };
    if (set && set.size) all[trackId] = [...set].sort((a, b) => a - b);
    else delete all[trackId];
    Store.setPref(FOLD_PREF, all);
    /* The tree is cached by key, and a fold changes which tree it is. */
    for (const k of Object.keys(treeCache)) {
      if (k === trackId || k.startsWith(`${trackId}|`)) delete treeCache[k];
    }
  }

  function trackTree(trackId, folded = null) {
    const t = track(trackId);
    if (!t) return null;

    const crs = courseOf(trackId);
    /* A fold only means anything for a course tree, where the chapters
       exist. Everything else ignores it. */
    const shut = crs && folded ? [...folded].filter(n => Number.isInteger(n)).sort((a, b) => a - b) : [];
    const key = shut.length ? `${trackId}|${shut.join(',')}` : trackId;
    if (treeCache[key]) return treeCache[key];

    /* Every concept the track's problems name, plus everything those rest
       on, transitively. chain() already closes over `needs`.

       For a course track the starting set is the course itself, so a
       chapter nothing has been set on yet is still in the picture. */
    const inSet = new Set();
    if (crs) {
      for (const cid of chapterConcepts(crs)) {
        if (!concepts[cid]) continue;
        for (const c of chain(cid)) inSet.add(c.id);
      }
    }
    for (const pid of t.problems) {
      const meta = byId[pid];
      if (!meta) continue;
      for (const cid of meta.prereqs || []) {
        for (const c of chain(cid)) inSet.add(c.id);
      }
    }

    /* A folded chapter is drawn as one box. Its concepts leave the
       graph and a synthetic node takes their place, inheriting every
       prerequisite that pointed into the chapter from outside and
       every dependent that pointed out of it — so the lines around it
       still say what they said. */
    const foldOf = {};        /* concept id -> synthetic node id */
    const synthetic = {};     /* synthetic node id -> { chapter, name, members } */
    if (crs && shut.length) {
      for (const ch of crs.chapters || []) {
        if (!shut.includes(ch.n)) continue;
        const members = (ch.concepts || []).filter(cid => inSet.has(cid));
        if (!members.length) continue;
        const nid = `__chapter-${ch.n}`;
        synthetic[nid] = { chapter: ch.n, title: ch.title, where: ch.where, members };
        for (const cid of members) foldOf[cid] = nid;
      }
    }
    const asNode = id => foldOf[id] || id;

    /* The prerequisites of a node, in the graph as it is being drawn:
       folded concepts are replaced by their chapter, and an edge from a
       chapter to itself is dropped rather than drawn as a self-loop. */
    const needsOf = (id) => {
      const raw = synthetic[id]
        ? synthetic[id].members.flatMap(m => (concepts[m] || {}).needs || [])
        : ((concepts[id] || {}).needs || []);
      const out = [];
      for (const n of raw) {
        if (!inSet.has(n)) continue;
        const to = asNode(n);
        if (to === id) continue;
        if (!out.includes(to)) out.push(to);
      }
      return out;
    };

    const measuring = new Set();
    const depths = {};
    function depth(id) {
      if (depths[id] !== undefined) return depths[id];
      if (measuring.has(id)) return 0;
      measuring.add(id);
      const ns = needsOf(id);
      const d = ns.length ? 1 + Math.max(...ns.map(depth)) : 0;
      measuring.delete(id);
      depths[id] = d;
      return d;
    }

    /* The nodes actually drawn: every unfolded concept, plus one box per
       folded chapter. */
    const ids = [...new Set([...inSet].map(asNode))];
    for (const id of ids) depth(id);

    const kids = {};
    const roots = [];
    const extra = {};
    for (const id of ids) {
      const ns = needsOf(id);
      if (!ns.length) { roots.push(id); continue; }
      /* Deepest parent, so every prerequisite is above this node. */
      const parent = ns.slice().sort((a, b) => depth(b) - depth(a))[0];
      extra[id] = ns.filter(n => n !== parent);
      (kids[parent] = kids[parent] || []).push(id);
    }

    const name = id => (synthetic[id]
      ? `Chapter ${synthetic[id].chapter}: ${synthetic[id].title}`
      : ((concepts[id] || {}).name || id));
    const byName = (a, b) => name(a).localeCompare(name(b));
    roots.sort(byName);
    for (const list of Object.values(kids)) list.sort(byName);

    /* How much of the track's own work sits at this node, so the tree can
       show progress without the reader opening every branch. */
    const own = new Set(t.problems);
    /* A folded chapter answers for every concept inside it: its
       readings, its exercises and its progress are the union of theirs,
       so folding hides detail and never hides work. */
    const problemsOf = (id) => {
      if (!synthetic[id]) return problemsForConcept(id);
      const seenP = new Set();
      const out = [];
      for (const m of synthetic[id].members) {
        for (const pr of problemsForConcept(m)) {
          if (seenP.has(pr.id)) continue;
          seenP.add(pr.id);
          out.push(pr);
        }
      }
      return out;
    };
    const readingsOf = (id) => {
      if (!synthetic[id]) return (concepts[id] || {}).readings || [];
      const out = [];
      const seenR = new Set();
      for (const m of synthetic[id].members) {
        for (const rd of (concepts[m] || {}).readings || []) {
          const k = `${rd.title}|${rd.where || rd.url || ''}`;
          if (seenR.has(k)) continue;
          seenR.add(k);
          out.push(rd);
        }
      }
      return out;
    };

    const build = (id, seen) => {
      const mine = problemsOf(id);
      const c = concepts[id] || {};
      const syn = synthetic[id] || null;
      return {
        id,
        name: name(id),
        oneLine: syn
          ? `${syn.members.length} ${syn.members.length === 1 ? 'section' : 'sections'}, folded into one. ${syn.where}`
          : (c.oneLine || ''),
        topic: syn ? (concepts[syn.members[0]] || {}).topic || '' : (c.topic || ''),
        /* Which chapter of its course this is, where in the notes it
           comes from, and whether the notes rule it out of the course. */
        chapter: syn ? syn.chapter : (c.chapter || null),
        where: syn ? syn.where : (c.where || ''),
        optional: syn
          ? syn.members.every(m => (concepts[m] || {}).optional)
          : !!c.optional,
        folded: syn ? syn.members.slice() : null,
        depth: depths[id] || 0,
        alsoNeeds: (extra[id] || []).map(n => ({ id: n, name: name(n) })),
        readings: readingsOf(id),
        problems: mine,
        inTrack: mine.filter(m => own.has(m.id)).length,
        /* A node reachable by two paths is drawn once, under the deepest
           parent, so the same subtree is never expanded twice. */
        children: (kids[id] || []).filter(k => !seen.has(k))
          .map(k => (seen.add(k), build(k, seen))),
      };
    };

    const seen = new Set(roots);
    const forest = roots.map(r => build(r, seen));
    treeCache[key] = {
      track: t, roots: forest, size: ids.length,
      course: crs,
      /* What the chapter rail draws: every chapter, whether it is
         folded, and how many of its concepts are actually in the tree. */
      chapters: crs ? (crs.chapters || []).map(ch => ({
        n: ch.n, title: ch.title, where: ch.where,
        folded: shut.includes(ch.n),
        concepts: (ch.concepts || []).filter(cid => inSet.has(cid)),
        optional: (ch.concepts || []).filter(cid => (concepts[cid] || {}).optional).length,
      })) : null,
    };
    return treeCache[key];
  }

  /* What a track is made of: readings, and then problems split four ways.

     The split is the point. A track's *required* work is the ordered list
     in data/tracks.json — that is what "8 of 12 solved" on the card and
     the progress bar both mean. But the tree is built from the concepts
     those problems rest on, and a concept is shared: `loop-invariants` is
     named by problems in four tracks. Everything else resting on a
     concept this track teaches is worth offering and is NOT part of
     finishing the track.

     Both used to be counted under a label reading "Problems", in two
     places on the same card, with different totals. Here they are
     `questions` and `coding` (required, and what the bar is a fraction
     of) and `related` (reachable through a shared concept, and not).

     `resources` is kept apart from all three and never added to them.
     Ticking a reading is a note to yourself that you have read it; it is
     not a graded thing and it is not evidence of anything. */
  function trackCounts(trackId) {
    const tree = trackTree(trackId);
    if (!tree) return null;

    const own = new Set(tree.track.problems || []);
    const seen = new Set();
    const out = {
      resources: { done: 0, total: 0 },
      questions: { done: 0, total: 0 },
      coding: { done: 0, total: 0 },
      related: { done: 0, total: 0 },
    };

    const solvedId = id => {
      const st = Store.record(id).status;
      return st === 'solved' || st === 'reviewed';
    };

    const count = meta => {
      /* A problem resting on two concepts in the same track is one
         problem, not two. */
      if (!meta || seen.has(meta.id)) return;
      seen.add(meta.id);
      const bucket = !own.has(meta.id) ? out.related
        : meta.type === 'code' ? out.coding
        : out.questions;
      bucket.total += 1;
      if (solvedId(meta.id)) bucket.done += 1;
    };

    (function walk(nodes) {
      for (const n of nodes) {
        const r = readProgress(n.id);
        out.resources.done += r.read;
        out.resources.total += r.total;
        for (const pr of n.problems) count(pr);
        walk(n.children);
      }
    })(tree.roots);

    /* A required problem that names no concept in the tree — one with an
       empty `prereqs` — is still required. Counting only what the tree
       reaches would make the card's total disagree with the bar beside
       it, which is the bug this function is here to not have. */
    for (const id of own) count(byId[id]);

    return out;
  }

  /* The required work alone, which is what "finished" means for a track:
     questions plus coding exercises in its own list. Resources and
     related practice are deliberately not in it. */
  function trackRequired(trackId) {
    const c = trackCounts(trackId);
    if (!c) return null;
    return {
      done: c.questions.done + c.coding.done,
      total: c.questions.total + c.coding.total,
    };
  }

  /* Readings ticked and problems solved beneath a node, itself included.
     Walked rather than stored, because both move as you work. */
  function treeProgress(node) {
    let read = 0; let readTotal = 0; let solved = 0; let probTotal = 0;
    (function walk(n) {
      const r = readProgress(n.id);
      read += r.read; readTotal += r.total;
      for (const pr of n.problems) {
        probTotal += 1;
        const st = Store.record(pr.id).status;
        if (st === 'solved' || st === 'reviewed') solved += 1;
      }
      n.children.forEach(walk);
    })(node);
    return { read, readTotal, solved, probTotal };
  }

  /* Unread / part-read / read, plus how much of the whole list is done. The
     status is per concept, which is the unit someone actually works through. */
  function readStatus(conceptId) {
    const p = readProgress(conceptId);
    if (!p.total) return { ...p, state: 'none' };
    if (p.read === 0) return { ...p, state: 'unread' };
    if (p.read >= p.total) return { ...p, state: 'read' };
    return { ...p, state: 'partly' };
  }

  const READ_STATE_LABEL = {
    none: 'No readings',
    unread: 'Unread',
    partly: 'Partly read',
    read: 'Read',
  };

  /* ---------------- what to do next ----------------

     The dashboard's main action, and the one question worth answering well:
     of eighty-five problems, which one now. In order of preference:

       1. something already started, in the track furthest along
       2. the next problem in that track
       3. the first problem of the first track not yet begun
       4. anything unsolved at all, easiest first
       5. nothing - everything is solved

     Returning the reason as well as the problem, because "picking up where you
     left off" and "starting a new track" deserve different wording. */
  function nextUp() {
    const open = allTracks()
      .map(t => ({ t, p: trackProgress(t) }))
      .filter(x => x.p.total && x.p.state !== 'completed');

    const started = open
      .filter(x => x.p.state === 'attempted')
      .sort((a, b) => b.p.fraction - a.p.fraction)[0];

    if (started) {
      const row = started.p.resume;
      if (row && row.meta) {
        return {
          meta: row.meta,
          track: started.t,
          progress: started.p,
          reason: row.record.status === 'unsolved' ? 'next-in-track' : 'resume',
        };
      }
    }

    const fresh = open.find(x => x.p.state === 'not-started');
    if (fresh && fresh.p.next && fresh.p.next.meta) {
      return { meta: fresh.p.next.meta, track: fresh.t, progress: fresh.p, reason: 'new-track' };
    }

    /* No track has anything left, but the catalogue might - tracks do not
       have to cover every problem. */
    const loose = sorted(index.filter(p => Store.record(p.id).status !== 'solved'))[0];
    if (loose) return { meta: loose, track: null, progress: null, reason: 'loose' };

    return null;
  }

  /* ---------------- counts ----------------

     Everything the copy on the page wants to say about how much is here. A
     sentence that says "nine topics" is a sentence that is wrong the next time
     a topic is added, so no view spells a number out. Counted over the index
     rather than over Store.TOPICS, so a topic with nothing in it yet is not
     advertised. */
  function counts() {
    const topics = new Set();
    const difficulties = new Set();
    const types = new Set();
    const langs = new Set();
    let code = 0;
    let minutes = 0;

    for (const p of index) {
      topics.add(p.topic);
      difficulties.add(p.difficulty);
      types.add(p.type);
      minutes += Number(p.estimate) || 0;
      if (p.type === 'code') {
        code += 1;
        for (const l of p.langs || []) langs.add(l);
      }
    }

    let readings = 0;
    for (const c of Object.values(concepts)) readings += (c.readings || []).length;
    for (const r of Object.values(resources.topics || {})) readings += (r.resources || []).length;

    return {
      problems: index.length,
      topics: topics.size,
      difficulties: difficulties.size,
      types: types.size,
      code,
      languages: langs.size,
      concepts: Object.keys(concepts).length,
      readings,
      tracks: tracks.length,
      minutes,
    };
  }

  return {
    init, all, meta, list, sorted, get, solution,
    concept, allConcepts, chain, prereqsFor, readProgress,
    allTracks, track, trackProgress, thisWeek, topicResources, allResources,
    counts, nextUp, problemsForConcept, readStatus, trackTree, treeProgress,
    allCourses, course, courseOf, foldedChapters, setFoldedChapters,
    trackCounts, trackRequired,
    TYPES, TYPE_BY_ID, TRACK_STATE_LABEL, READ_STATE_LABEL,
    LANGS, LANG_LABEL, registerPool, isPooled, WRITTEN_TYPES, TYPE_WORDS,
    get loadError() { return loadError; },
  };
})();
