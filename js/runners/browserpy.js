/* ============================================================
   runners/browserpy.js — Python on this device, with nothing
   installed and nothing paid for.

   CPython 3.14.2 compiled to WebAssembly (Pyodide 314.0.7),
   running in a worker in this tab. 12.8 MB, fetched the first
   time somebody presses Run on a Python problem and cached
   afterwards; about a second to start and milliseconds per case.

   A seventh of the C++ toolchain, and the same bargain: no
   runner to install, no Docker, no WSL, no API key, nothing
   leaves the machine.

   The shape of a run:

     run worker   long-lived, holds the interpreter; each case
                  gets a fresh globals dict, and a timeout or a
                  cancellation terminates the whole worker

   This answers in exactly the shape the local runner, the
   hosted proxy and the browser C++ runner answer in, so nothing
   downstream can tell which produced a verdict — except that it
   says so.

   What it cannot do is in js/py/interpreter.js and is taken
   seriously: 32-bit sys.maxsize, sys.platform of 'emscripten',
   no real filesystem, no processes, no threads, standard
   library only. data/py-support.json says which problems are
   certified for it, and that file is generated by running every
   one of them rather than by anybody's judgement.
   ============================================================ */

const BrowserPy = (() => {

  /* Same trick as browsercpp.js: the site loads plain <script> tags, so
     import.meta does not exist here and the worker URL has to be
     resolved against the script's own src. */
  const HERE = (() => {
    const self = document.currentScript && document.currentScript.src;
    return self ? new URL('.', self).href : new URL('js/runners/', location.href).href;
  })();
  const workerUrl = name => new URL(`../py/${name}`, HERE).href;
  const assetBase = () => new URL('../../vendor/py/', HERE).href;

  const BOOT_MS = 120_000;     /* the first one includes 12.8 MB */
  const RUN_MS = 5_000;        /* per case, matching the local runner */
  const MAX_SOURCE = 256 * 1024;

  const RUNTIME = Object.freeze({
    implementation: 'CPython 3.14.2',
    target: 'wasm32-emscripten',
    via: 'Pyodide 314.0.7',
  });

  /* Loaded once, lazily. The *promise* is what is cached, not a flag:
     setting a flag before awaiting means a second caller arriving while
     the fetch is still out gets the not-yet-loaded value, decides the
     language is uncertified, and disables its tab. That is exactly what
     happened — the first paint of the toolbar and the first describe()
     race each other on every page load. */
  let supportPromise = null;

  function loadSupport() {
    if (!supportPromise) {
      supportPromise = fetch(new URL('../../data/py-support.json', HERE).href,
        { cache: 'no-cache' })
        .then(res => (res.ok ? res.json() : null))
        .catch(() => null);
    }
    return supportPromise;
  }

  function capable() {
    return typeof Worker !== 'undefined'
      && typeof WebAssembly !== 'undefined'
      && typeof WebAssembly.compile === 'function';
  }

  async function supportsProblem(problemId) {
    if (!problemId) return false;
    const s = await loadSupport();
    return !!(s && Array.isArray(s.browser) && s.browser.includes(problemId));
  }

  async function reasonFor(problemId) {
    const s = await loadSupport();
    if (!s) return null;
    const why = (s.nativeOnly || {})[problemId];
    return why || null;
  }

  const toolchain = () => RUNTIME;

  /* ---------------- the worker ---------------- */

  let worker = null;
  let booting = null;
  let ready = false;
  let loaded = 0;
  let progressFn = null;

  const onProgress = fn => { progressFn = fn; };
  const progress = () => ({ loaded, total: 12_800_000 });

  function teardown() {
    if (worker) { try { worker.terminate(); } catch { /* already gone */ } }
    worker = null;
    booting = null;
    ready = false;
    loaded = 0;
  }

  /* Starts the interpreter, or returns the start already in flight.
     Anything that goes wrong tears the worker down rather than leaving a
     half-booted one for the next press of Run to inherit. */
  function prepare({ signal } = {}) {
    if (ready) return Promise.resolve();
    if (booting) return booting;

    booting = new Promise((resolve, reject) => {
      let settled = false;
      const finish = (err) => {
        if (settled) return;
        settled = true;
        clearTimeout(timer);
        if (err) { teardown(); reject(err); } else { ready = true; resolve(); }
      };

      const timer = setTimeout(
        () => finish(new Error('the interpreter took too long to start')), BOOT_MS);

      try {
        worker = new Worker(workerUrl('run.worker.js'), { type: 'module' });
      } catch (err) {
        finish(new Error(`a worker could not be started: ${err.message}`));
        return;
      }

      worker.onerror = e => finish(new Error(e.message || 'the worker failed'));
      worker.onmessage = e => {
        const m = e.data || {};
        if (m.type === 'progress') {
          loaded += m.loaded;
          if (progressFn) progressFn({ loaded, total: m.total, cached: m.cached });
        } else if (m.type === 'ready') {
          finish(null);
        } else if (m.type === 'failed') {
          finish(new Error(m.error));
        }
      };

      if (signal) {
        signal.addEventListener('abort',
          () => finish(new Error('cancelled')), { once: true });
      }

      worker.postMessage({ type: 'boot', base: assetBase() });
    });

    return booting;
  }

  /* One case. Resolves with a result, or rejects — a timeout and a
     cancellation both take the worker with them, because a wasm loop
     yields to nothing and terminate() is the only thing that ends it. */
  function runOne(source, stdin, { runMs = RUN_MS, signal } = {}) {
    return new Promise((resolve, reject) => {
      if (!worker || !ready) { reject(new Error('the interpreter is not up')); return; }

      const w = worker;
      let settled = false;
      const done = (err, value) => {
        if (settled) return;
        settled = true;
        clearTimeout(timer);
        if (signal) signal.removeEventListener('abort', onAbort);
        w.onmessage = prev;
        if (err) reject(err); else resolve(value);
      };

      const onAbort = () => { teardown(); done(new Error('cancelled')); };
      const timer = setTimeout(() => {
        teardown();
        done(Object.assign(new Error('timed out'), { timedOut: true }));
      }, runMs);

      const prev = w.onmessage;
      w.onmessage = e => {
        const m = e.data || {};
        if (m.type === 'done') done(null, m.result);
        else if (m.type === 'failed') done(new Error(m.error));
      };

      if (signal) {
        if (signal.aborted) { onAbort(); return; }
        signal.addEventListener('abort', onAbort, { once: true });
      }

      w.postMessage({ type: 'run', source, stdin, limits: { runMs } });
    });
  }

  /* ---------------- the shape everything downstream expects ---------------- */

  const down = why => ({
    lang: 'python', backend: 'browserpy',
    compile: { ok: false, stdout: '', stderr: '', ms: 0, timedOut: false },
    cases: [], judgeDown: true,
    judgeError: `The in-browser interpreter could not be used: ${why}.`,
  });

  /* judgeDown and a judgeError, exactly as browsercpp does it: that pair
     is what makes the result pane say something rather than report "0 of
     0 cases passed", which is what a cancelled run looked like before. */
  const cancelled = () => ({
    lang: 'python', backend: 'browserpy',
    compile: { ok: false, stdout: '', stderr: '', ms: 0, timedOut: false },
    cases: [], judgeDown: true, cancelled: true,
    judgeError: 'Stopped. Nothing was recorded, and your code is as you left it.',
  });

  async function run(source, cases, { runMs = RUN_MS, signal, onStage } = {}) {
    const say = s => { if (onStage) onStage(s); };

    if (!capable()) return down('this browser cannot run WebAssembly in a worker');
    if (String(source || '').length > MAX_SOURCE) {
      return down(`the source is larger than ${Math.round(MAX_SOURCE / 1024)} KB`);
    }

    try {
      if (!ready) say('downloading');
      await prepare({ signal });
    } catch (err) {
      if (signal && signal.aborted) return cancelled();
      if (err && err.name === 'AbortError') return cancelled();
      return down(err.message);
    }

    say('running');
    const results = [];
    for (let i = 0; i < (cases || []).length; i += 1) {
      if (signal && signal.aborted) return cancelled();
      const c = cases[i];
      /* eslint-disable-next-line no-await-in-loop -- sequential on purpose:
         one interpreter, and an early abort should not leave another case
         about to start. */
      const r = await runOne(source, c.stdin || '', { runMs, signal }).catch(err => err);

      if (r instanceof Error) {
        if (r.message === 'cancelled') return cancelled();
        /* A timeout took the worker with it, so the interpreter has to come
           back before the next case. From cache that is about a second. */
        results.push({
          stdout: '',
          stderr: r.timedOut ? '' : String(r.message),
          exit: r.timedOut ? 124 : 1,
          signal: null,
          timedOut: !!r.timedOut,
          ms: runMs,
        });
        if (i + 1 < (cases || []).length) {
          /* eslint-disable-next-line no-await-in-loop -- see above. */
          const back = await prepare({ signal }).then(() => true, () => false);
          if (!back) return { ...blank(), cases: results, judgeDown: true,
            judgeError: 'The in-browser interpreter did not restart.' };
        }
        continue;
      }

      results.push({
        stdout: r.stdout,
        /* Truncation is the harness's doing, not the program's, so it is
           said in the output rather than silently dropped. */
        stderr: r.truncated ? `${r.stderr}\n[output truncated]` : r.stderr,
        exit: r.status,
        signal: null,
        timedOut: false,
        ms: r.ms,
      });
    }

    return { ...blank(), cases: results };
  }

  /* Python has no build step, so "it built" is always true. Saying so in
     the same shape the compiled languages use keeps every reader
     downstream — the judge, the UI — from special-casing it.

     Note what is *not* here: pass, why, expect. Judging is
     js/runners/harness.js's job for every backend, and a second
     implementation of it here is how two backends come to disagree about
     what counts as a correct answer. */
  const blank = () => ({
    lang: 'python',
    backend: 'browserpy',
    compile: { ok: true, stdout: '', stderr: '', ms: 0, timedOut: false },
    cases: [],
  });

  return {
    capable, supportsProblem, reasonFor, loadSupport, toolchain,
    prepare, onProgress, progress, teardown, run,
    get ready() { return ready; },
    /* Exposed for the browser tests, which drive a run without a page. */
    runOne,
    TOTAL_MB: 13,
  };
})();
