/* ============================================================
   runners/probe.js — grading a requirement that the output
   cannot show.

   Most exercises here are graded by feeding a program some input
   and comparing what it prints. That is a complete check of the
   program's behaviour and a very incomplete check of the
   exercise. "Write a function `power(base, exponent = 2)` and
   call it with one argument" is a requirement about the shape of
   the code, and a program that hard-codes `power(base, 2)` — or
   never writes a function at all and does the work inline —
   prints exactly the same characters.

   Three of the beginner C++ exercises said so in their statements
   and left it there. This is the part that stops saying so and
   checks.

   The idea is the one a unit test uses: compile the submitted
   program together with a `main` the PROBLEM owns, which calls
   the functions the statement asked for and prints what it got
   back. The submitted `main` is renamed and never runs, so the
   calls are the grader's own:

       #include <iostream>          <- hoisted from the submission
       #define main <renamed>
       #line 1 "your-program.cpp"
       ...the submission, verbatim...
       #undef main
       #line 1 "interface-check.cpp"
       int main() { std::cout << power(7) << "\n"; }

   Two consequences worth being plain about:

     · A submission that does not define the function with a
       compatible signature does not COMPILE here. That is the
       check working, not a bug, and the verdict says which name
       it could not call.

     · What this still cannot see is which calls the submission's
       own `main` makes. `power(base)` and `power(base, 2)` are
       indistinguishable from outside. So the probe checks that
       the default argument EXISTS and is 2 — which is the part
       that is checkable — and the statement says the rest is on
       the reader. A grader that claimed more than this would be
       lying about a technique it cannot observe.

   Nothing here touches the DOM, the network or a Worker: compose
   makes a string and fold folds one reply into one verdict, so
   both are unit-tested in node.
   ============================================================ */

const RunProbe = (() => {

  /* The submitted `main` becomes this. Not `__`-prefixed: names with two
     leading underscores are reserved to the implementation, and a grader
     has no business claiming one. */
  const RENAMED = 'invariant_submission_main';

  /* Always present, because the probe body itself prints and may build a
     vector or a string whatever the submission included. */
  const BASE = ['<iostream>', '<string>', '<vector>'];

  /* Only the angle-bracket form, one header per line, nothing else on the
     line. A quoted include names a file that does not exist in a
     single-file exercise, and would have failed the ordinary cases long
     before this. */
  const INCLUDE = /^[ \t]*#[ \t]*include[ \t]*(<[A-Za-z0-9_./+-]+>)[ \t]*$/;

  /* Every header the submission asks for, hoisted above the rename.

     This is the whole reason the `#define main` is safe. Defined over a
     header's text it would rewrite whatever that header calls `main`;
     included FIRST, every header the submission names is already in and
     its include guard makes the submission's own directive a no-op, so
     the macro never reaches library code at all. */
  function headers(source) {
    const seen = new Set(BASE);
    for (const line of String(source == null ? '' : source).split('\n')) {
      const m = INCLUDE.exec(line);
      if (m) seen.add(m[1]);
    }
    return [...seen];
  }

  /* One translation unit: the submission, unchanged except for the name of
     its `main`, and the problem's own `main` after it. */
  function compose(probeSource, submitted, { renamed = RENAMED } = {}) {
    const code = String(submitted == null ? '' : submitted).replace(/\r\n?/g, '\n');
    return [
      '/* Generated by the grader: the submitted program, plus a main the',
      '   exercise owns. The submitted main is renamed and never called. */',
      ...headers(code).map(h => `#include ${h}`),
      '',
      `#define main ${renamed}`,
      '#line 1 "your-program.cpp"',
      code.endsWith('\n') ? code.slice(0, -1) : code,
      '#undef main',
      '#line 1 "interface-check.cpp"',
      String(probeSource == null ? '' : probeSource).replace(/\r\n?/g, '\n'),
      '',
    ].join('\n');
  }

  /* Whether a problem has one of these, and whether this submission is the
     kind it can be applied to. A workspace is already several translation
     units with their own entry point; renaming one file's `main` is not a
     question that has an answer there, and no workspace exercise needs it. */
  function has(key, response) {
    const probe = (key || {}).probe;
    if (!probe || !probe.source || !Array.isArray(probe.cases) || !probe.cases.length) return false;
    if (!response || response.files) return false;
    return (probe.langs || ['cpp']).includes(response.lang);
  }

  const cases = probe => (probe.cases || []).map((c, i) => ({
    stdin: c.stdin || '',
    expect: c.expect == null ? '' : c.expect,
    label: c.label || `Direct call ${i + 1}`,
    calls: c.calls || probe.calls || '',
  }));

  /* The first line of a compiler's answer that a reader can act on, with
     the generated file's name taken off the front — "interface-check.cpp"
     is a file nobody has, and leading with it sends them looking for it. */
  function firstError(stderr) {
    const line = String(stderr || '').split('\n').find(l => /error:/.test(l));
    if (!line) return '';
    return line.replace(/^.*?error:\s*/, '').trim();
  }

  /* Fold one probe reply into the verdict the ordinary cases produced.

     The verdict is mutated and returned, because it is the thing the page
     has already been handed and the one the submission records. */
  function fold(verdict, reply, probe, { judge = (typeof RunHarness !== 'undefined' ? RunHarness : null) } = {}) {
    const want = cases(probe);
    const compile = (reply && reply.compile) || { ok: false, stderr: '' };
    verdict.probe = { ran: true, built: !!compile.ok };

    if (!compile.ok) {
      /* The submission compiled on its own — it has to have, or the
         ordinary cases could not have passed — so this is a mismatch
         between what it defines and what the statement asked for. */
      const why = firstError(compile.stderr);
      verdict.cases.push({
        stdout: '', stderr: String(compile.stderr || '').trim(),
        exit: -1, signal: null, timedOut: false, ms: 0, sanitizer: false,
        expect: want[0] ? want[0].expect : '',
        pass: false,
        label: probe.label || 'Direct call',
        calls: want[0] ? want[0].calls : '',
        why: `The grader could not call your code${why ? `: ${why}` : '.'}`,
      });
    } else {
      const results = (reply.cases || []).map((r, i) =>
        Object.assign(judge.judgeCase(r, want[i] ? want[i].expect : ''), {
          label: want[i] ? want[i].label : `Direct call ${i + 1}`,
          calls: want[i] ? want[i].calls : '',
        }));
      verdict.cases.push(...results);
    }

    const passed = verdict.cases.filter(c => c.pass).length;
    const total = verdict.cases.length;
    verdict.passed = passed;
    verdict.score = total ? passed / total : 0;
    verdict.correct = total > 0 && passed === total;

    if (verdict.correct) {
      verdict.feedback = `All ${total} ${total === 1 ? 'check' : 'checks'} passed, `
        + 'including the ones that call your functions directly.';
    } else {
      const first = verdict.cases.find(c => !c.pass);
      verdict.feedback = 'Every input case passed, and a direct call did not. '
        + (first ? first.why : '');
    }

    return verdict;
  }

  return { compose, headers, has, cases, fold, firstError, RENAMED, BASE };
})();

if (typeof globalThis !== 'undefined') globalThis.RunProbe = RunProbe;
